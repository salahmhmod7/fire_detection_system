"""
YOLO Execution Engine
Manages the model initialization and the training loop.
"""
import logging
from pathlib import Path
from ultralytics import YOLO

logger = logging.getLogger(__name__)

class ModelTrainer:
    def __init__(self, root_dir: Path, model_version: str = "yolo11s.pt"):
        self.root_dir = root_dir
        self.data_yaml = root_dir / "data" / "processed" / "data.yaml"
        self.project_dir = root_dir / "runs" / "train"
        self.model_version = model_version
        self.model = None

    def initialize_model(self):
        logger.info(f"Initializing YOLO model with base weights: {self.model_version}")
        # Automatically downloads the pre-trained weights if not present
        self.model = YOLO(self.model_version)

    def train(self, epochs: int, batch_size: int, imgsz: int, hyperparams: dict) -> Path:
        if not self.data_yaml.exists():
            raise FileNotFoundError(f"Missing dataset config: {self.data_yaml}. Run Phase 1 first.")

        logger.info(f"Starting training for {epochs} epochs at {imgsz}x{imgsz} resolution...")
        
        # Merge custom hyperparameters into the training call
        results = self.model.train(
            data=str(self.data_yaml),
            epochs=epochs,
            batch=batch_size,
            imgsz=imgsz,
            project=str(self.project_dir),
            name="fire_smoke_v1",
            exist_ok=True,         # Overwrite if we restart the exact same named run
            patience=20,           # Early stopping if no improvement for 20 epochs
            save=True,
            save_period=10,        # Save checkpoints every 10 epochs
            cache=False,           # Disabled RAM caching to prevent memory overload
            workers=2,             # Limit workers to ensure stability on System RAM
            **hyperparams
        )
        
        # The path to the best weights generated by this run
        best_weights = self.project_dir / "fire_smoke_v1" / "weights" / "best.pt"
        logger.info(f"Training completed successfully. Best weights saved to: {best_weights}")
        return best_weights